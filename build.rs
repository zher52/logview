//! 构建期把 `locales/*.toml` 编译成 `&'static str` 查表。
//!
//! 好处：译文可在不写 Rust 的情况下维护，同时运行时零解析开销；
//! 三种语言的键集合必须一致，缺项直接编译失败，避免运行时静默回退。

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::PathBuf;

const LANGS: [&str; 3] = ["zh", "en", "ru"];

fn main() {
    let root = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    println!("cargo:rerun-if-changed=locales");

    let mut tables: Vec<BTreeMap<String, String>> = Vec::new();
    for lang in LANGS {
        let path = root.join("locales").join(format!("{lang}.toml"));
        println!("cargo:rerun-if-changed={}", path.display());
        let text = std::fs::read_to_string(&path)
            .unwrap_or_else(|e| panic!("读取 {} 失败: {e}", path.display()));
        let table: toml::Table =
            toml::from_str(&text).unwrap_or_else(|e| panic!("解析 {} 失败: {e}", path.display()));
        let mut map = BTreeMap::new();
        for (k, v) in table {
            let Some(s) = v.as_str() else {
                panic!("{lang}.toml: 键 {k} 的值不是字符串");
            };
            if s.trim().is_empty() {
                panic!("{lang}.toml: 键 {k} 的译文为空");
            }
            map.insert(k, s.to_string());
        }
        tables.push(map);
    }

    // 以中文键集合为准校验另外两种语言：缺项、多项都视为错误
    let zh = &tables[0];
    for (i, lang) in LANGS.iter().enumerate().skip(1) {
        let table = &tables[i];
        let missing: Vec<&String> = zh.keys().filter(|k| !table.contains_key(*k)).collect();
        let extra: Vec<&String> = table.keys().filter(|k| !zh.contains_key(*k)).collect();
        if !missing.is_empty() || !extra.is_empty() {
            let mut msg = format!("{lang}.toml 与 zh.toml 的键不一致");
            if !missing.is_empty() {
                write!(
                    msg,
                    "; 缺少 {} 项: {:?}",
                    missing.len(),
                    &missing[..missing.len().min(8)]
                )
                .unwrap();
            }
            if !extra.is_empty() {
                write!(
                    msg,
                    "; 多出 {} 项: {:?}",
                    extra.len(),
                    &extra[..extra.len().min(8)]
                )
                .unwrap();
            }
            panic!("{msg}");
        }
    }

    // 中文原文 → ID 的反查表：供 td() 翻译运行时字符串与历史数据（预设名、配置名）
    let mut idx: Vec<(String, String)> = Vec::new();
    for (id, text) in zh {
        // 复数变体只是同一中文模板的副本，不参与反查
        if [".one", ".few", ".other", ".many"]
            .iter()
            .any(|s| id.ends_with(s))
        {
            continue;
        }
        idx.push((text.clone(), id.clone()));
    }
    idx.sort();
    for w in idx.windows(2) {
        if w[0].0 == w[1].0 {
            panic!(
                "中文原文重复，td() 无法唯一反查: {:?} -> {} / {}",
                w[0].0, w[0].1, w[1].1
            );
        }
    }

    let mut out = String::from("// @generated by build.rs from locales/*.toml\n");
    for (i, lang) in LANGS.iter().enumerate() {
        let name = match *lang {
            "zh" => "ZH",
            "en" => "EN",
            _ => "RU",
        };
        writeln!(out, "pub const {name}: &[(&str, &str)] = &[").unwrap();
        // BTreeMap 已按键排序，运行时用 binary_search 查找
        for (k, v) in &tables[i] {
            writeln!(out, "    ({k:?}, {v:?}),").unwrap();
        }
        writeln!(out, "];\n").unwrap();
    }
    writeln!(out, "/// 全部合法 ID（构建期已校验三语一致）").unwrap();
    writeln!(out, "#[allow(dead_code)]").unwrap();
    writeln!(out, "pub const IDS: &[&str] = &[").unwrap();
    for id in zh.keys() {
        writeln!(out, "    {id:?},").unwrap();
    }
    writeln!(out, "];\n").unwrap();
    writeln!(out, "/// 中文原文 → ID，用于运行时字符串翻译（td）").unwrap();
    writeln!(out, "pub const ZH_INDEX: &[(&str, &str)] = &[").unwrap();
    for (text, id) in &idx {
        writeln!(out, "    ({text:?}, {id:?}),").unwrap();
    }
    writeln!(out, "];").unwrap();

    let dest = PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("locales.rs");
    std::fs::write(&dest, out).unwrap();
}
